def style(run, bold=False, size=10, color=None):
    run.font.name = "맑은 고딕"; run._element.rPr.rFonts.set(qn("w:eastAsia"), "맑은 고딕")
    run.font.size = Pt(size); run.bold = bold
    if color: run.font.color.rgb = RGBColor.from_string(color)
def set_cell(cell, text, bold=False):
    for p in cell.paragraphs[1:]: p._element.getparent().remove(p._element)
    p = cell.paragraphs[0]
    for r in p.runs[1:]: r._element.getparent().remove(r._element)
    r = p.runs[0] if p.runs else p.add_run(); r.text = text; style(r, bold)
def add_lines(cell, lines):
    for ln in lines:
        p = cell.add_paragraph()
        if isinstance(ln, tuple): txt, b, col = ln[0], ln[1], (ln[2] if len(ln) > 2 else None)
        else: txt, b, col = ln, False, None
        style(p.add_run(txt), b, 10, col)

