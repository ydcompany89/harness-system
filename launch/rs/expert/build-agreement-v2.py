def para(text='', bold=False, size=None, align=None, indent=None, before=None, color=None, italic=False):
    p = doc.add_paragraph()
    if align: p.alignment = align
    if indent is not None: p.paragraph_format.left_indent = Cm(indent)
    if before is not None: p.paragraph_format.space_before = Pt(before)
    if text:
        r = p.add_run(text); r.bold = bold; r.italic = italic
        if size: r.font.size = Pt(size)
        if color: r.font.color.rgb = color
    return p

def shade(cell, hex_):
    tcPr = cell._tc.get_or_add_tcPr(); sh = OxmlElement('w:shd')
    sh.set(qn('w:val'), 'clear'); sh.set(qn('w:color'), 'auto'); sh.set(qn('w:fill'), hex_); tcPr.append(sh)

def table(rows, widths, header=True):
    t = doc.add_table(rows=len(rows), cols=len(rows[0])); t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER; t.autofit = False
    for j, gc in enumerate(t._tbl.tblGrid.findall(qn('w:gridCol'))): gc.set(qn('w:w'), str(int(widths[j] * 567)))
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            c = t.cell(i, j); c.width = Cm(widths[j]); c.text = ''
            r = c.paragraphs[0].add_run(v); r.font.size = Pt(9.5)
            if v == '☐': c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
            if header and i == 0: r.bold = True; shade(c, 'EDEDED')
    doc.add_paragraph(); return t

def article(title, items):
    para(title, bold=True, before=8)
    for it in items:
        if isinstance(it, tuple): para(it[1], indent=it[0])
        else: para(it, indent=0.3)

